/* Which sizing chart a product uses. The catalogue's own `cut` field is the
   authority ("Short sleeve" / "Long sleeve", present on the 12 team jerseys
   only); the slug is a fallback. Anything else returns null and keeps the
   generic guide. */
window.IDL_JERSEY_GARMENT = function (key, product) {
  var cut = product && product.cut;
  if (!cut && key) {
    if (key.indexOf('short-sleeve') !== -1) cut = 'Short sleeve';
    else if (key.indexOf('long-sleeve') !== -1) cut = 'Long sleeve';
  }
  if (cut === 'Short sleeve') return 'ss-jersey';
  if (cut === 'Long sleeve') return 'ls-jersey';
  return null;
};
